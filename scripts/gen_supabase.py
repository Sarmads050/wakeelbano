# -*- coding: utf-8 -*-
"""Generate supabase/seed.sql from scripts/jobs_data.py.

Run after editing the job, task or lawyer data:
    python3 scripts/gen_supabase.py
"""
import io, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from jobs_data import JOBS, TASKS, LAWYERS  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def q(v):
    if v is None:
        return "null"
    return "'" + str(v).replace("'", "''") + "'"


def arr(v):
    if not v:
        return "'{}'"
    inner = ",".join('"' + str(x).replace('"', '\\"') + '"' for x in v)
    return "'{" + inner + "}'"


def main():
    out = ["-- WakeelBano seed data — generated by scripts/gen_supabase.py",
           "-- Safe to re-run: every insert upserts on the primary key.", ""]

    out.append("-- jobs")
    for j in JOBS:
        out.append(
            "insert into public.jobs (id, title, org, city, area, job_type, experience, pay, "
            "description, tags, source, source_url, posted_at, status) values ("
            f"{q(j['id'])}, {q(j['t'])}, {q(j['org'])}, {q(j['city'])}, {q(j['area'])}, "
            f"{q(j['type'])}, {q(j['exp'])}, {q(j['pay'])}, {q(j['desc'])}, {arr(j.get('tags'))}, "
            f"{q(j['src'])}, {q(j['url'])}, {q(j['posted'])}, 'live') "
            "on conflict (id) do update set title = excluded.title, org = excluded.org, "
            "city = excluded.city, area = excluded.area, job_type = excluded.job_type, "
            "experience = excluded.experience, pay = excluded.pay, description = excluded.description, "
            "tags = excluded.tags, source = excluded.source, source_url = excluded.source_url, "
            "posted_at = excluded.posted_at, status = excluded.status;")

    out += ["", "-- tasks"]
    for t in TASKS:
        out.append(
            "insert into public.tasks (id, title, category, city, pay, turnaround, posted_for, description) values ("
            f"{q(t['id'])}, {q(t['t'])}, {q(t['cat'])}, {q(t['city'])}, {q(t['pay'])}, "
            f"{q(t['days'])}, {q(t['by'])}, {q(t['desc'])}) "
            "on conflict (id) do update set title = excluded.title, category = excluded.category, "
            "city = excluded.city, pay = excluded.pay, turnaround = excluded.turnaround, "
            "posted_for = excluded.posted_for, description = excluded.description;")

    out += ["", "-- lawyers"]
    for l in LAWYERS:
        out.append(
            "insert into public.lawyers (id, name, city, area, chamber, enrolled, cases, skills, "
            "rate, bio, verified, seed_rating, seed_reviews) values ("
            f"{q(l['id'])}, {q(l['n'])}, {q(l['city'])}, {q(l['area'])}, {q(l['chamber'])}, "
            f"{l['since']}, {l['cases']}, {arr(l['skills'])}, {q(l['rate'])}, {q(l['bio'])}, "
            f"{str(l['verified']).lower()}, {l['rating']}, {l['reviews']}) "
            "on conflict (id) do update set name = excluded.name, city = excluded.city, "
            "area = excluded.area, chamber = excluded.chamber, cases = excluded.cases, "
            "skills = excluded.skills, rate = excluded.rate, bio = excluded.bio, "
            "verified = excluded.verified, seed_rating = excluded.seed_rating, "
            "seed_reviews = excluded.seed_reviews;")

    out += ["", "select 'jobs' as table_name, count(*) from public.jobs",
            "union all select 'tasks', count(*) from public.tasks",
            "union all select 'lawyers', count(*) from public.lawyers;", ""]

    path = os.path.join(ROOT, "supabase", "seed.sql")
    io.open(path, "w", encoding="utf-8").write("\n".join(out))
    print(f"supabase/seed.sql written: {len(JOBS)} jobs, {len(TASKS)} tasks, {len(LAWYERS)} lawyers")


if __name__ == "__main__":
    main()
